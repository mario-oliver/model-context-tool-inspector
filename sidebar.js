let trace = [];

async function promptAI() {
  const [tab] = await chrome.tabs.query({ active: true, currentWindow: true });

  chat ??= genAI.chats.create({ model: localStorage.model });

  const message = userPromptText.value;
  userPromptText.value = '';
  lastSuggestedUserPrompt = '';
  logPrompt('user', { text: message });
  const sendMessageParams = { message, config: getConfig() };
  trace.push({ userPrompt: sendMessageParams });
  let currentResult = await chat.sendMessage(sendMessageParams);
  let finalResponseGiven = false;

  while (!finalResponseGiven) {
    const response = currentResult;
    trace.push({ response });
    const functionCalls = response.functionCalls || [];

    if (functionCalls.length === 0) {
      if (!response.text) {
        logPrompt('warning', { text: `AI response has no text: ${JSON.stringify(response.candidates)}` });
      } else {
        logPrompt('assistant', { text: response.text?.trim() });
      }
      finalResponseGiven = true;
    } else {
      const toolResponses = [];
      for (const { name: toolName, args } of functionCalls) {
        let [frameId, name] = toolName.split(/_(.*)/s)[1].split(/_(.*)/s);
        frameId = parseInt(frameId);
        const inputArgs = JSON.stringify(args);
        const declared = currentTools?.find((t) => t.name === name);
        const toolEvent = logPrompt('toolCall', {
          toolName: name,
          frameId,
          inputSchema: declared?.inputSchema,
          destructive: isDestructive(declared),
          proposedArgs: args,
          sentArgs: args,
        });
        // Issue 0002: page URL either side of the call. Sidebar-side only —
        // content.js is not involved, we already hold tab.id here.
        const urlBefore = await tabUrl(tab.id);
        const startedAt = Date.now();
        try {
          const result = await executeTool(tab.id, name, inputArgs, frameId);
          toolResponses.push({ functionResponse: { name: toolName, response: { result } } });
          logPrompt(toolEvent, {
            status: 'ok',
            result,
            urlBefore,
            urlAfter: await tabUrl(tab.id),
            durationMs: Date.now() - startedAt,
          });
        } catch (e) {
          const urlAfter = await tabUrl(tab.id);
          // A call whose result was destroyed by navigation DID run, and may have
          // had side effects. Reporting it as `error` reads as "nothing happened",
          // which is the opposite of the truth. See context.md#Lost result.
          const status = isLostToNavigation(e) ? 'lost' : 'error';
          logPrompt(toolEvent, {
            status,
            errorMessage: e.message,
            urlBefore,
            urlAfter,
            durationMs: Date.now() - startedAt,
          });
          toolResponses.push({
            functionResponse: { name: toolName, response: { error: e.message } },
          });
        }
      }

      const sendMessageParams = { message: toolResponses, config: getConfig() };
      trace.push({ userPrompt: sendMessageParams });
      currentResult = await chat.sendMessage(sendMessageParams);
    }
  }
}

