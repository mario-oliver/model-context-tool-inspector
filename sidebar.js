async function executeTool(tabId, name, inputArgs, frameId) {
  let toolsReady;
  const toolsPromise = new Promise((resolve) => {
    toolsReady = resolve;
  });

  let targetTabId = tabId;
  let contentScriptReadyResolve;
  const contentScriptReadyPromise = new Promise((r) => { contentScriptReadyResolve = r; });

  const listener = (msg, sender) => {
    if (msg.type === 'contentScriptReady' && sender.tab) {
      if (sender.tab.id === tabId || sender.tab.openerTabId === tabId) {
        targetTabId = sender.tab.id;
        contentScriptReadyResolve();
      }
    }
    if (msg.tools && sender.tab?.id === targetTabId) {
      toolsReady();
    }
  };
  chrome.runtime.onMessage.addListener(listener);

  try {
    try {
      const result = await chrome.tabs.sendMessage(
        tabId,
        { action: 'EXECUTE_TOOL', name, inputArgs },
        { frameId },
      );
      if (result !== null) return result;
    } catch (error) {
      if (!/message channel (is )?closed/.test(error.message)) throw error;
    }

    // A navigation was triggered. The result will be on the next document,
    // which may live in a new tab if the tool opened one.
    await Promise.race([
      contentScriptReadyPromise,
      new Promise((r) => setTimeout(r, 2000)),
    ]);

    await Promise.race([
      toolsPromise,
      new Promise((r) => setTimeout(r, 2000)),
    ]);

    await waitForPageLoad(targetTabId);

    return await chrome.tabs.sendMessage(
      targetTabId,
      { action: 'GET_CROSS_DOCUMENT_SCRIPT_TOOL_RESULT' },
      // The original frameId only makes sense in the original tab.
      { frameId: targetTabId === tabId ? frameId : 0 },
    );
  } finally {
    chrome.runtime.onMessage.removeListener(listener);
  }
}

toolNames.onchange = updateDefaultValueForInputArgs;

function updateDefaultValueForInputArgs() {
  const inputSchema = toolNames.selectedOptions[0].dataset.inputSchema || '{}';
  const template = generateTemplateFromSchema(JSON.parse(inputSchema));
  inputArgsText.value = JSON.stringify(template, '', ' ');
}

// Utils

// The seam (context.md#The seam): all Event emission happens here. A string
// first argument creates a new Event of that kind; passing back the Event
// returned from an earlier call updates it in place instead — that's how the
// "calling tool" and "result"/"error" call sites end up as one Event.
function logPrompt(kindOrEvent, data) {
  return typeof kindOrEvent === 'string'
    ? Transcript.append(kindOrEvent, data)
    : Transcript.update(kindOrEvent, data);
}

/** Current URL of a tab, or undefined if it can't be read. Never throws. */
async function tabUrl(tabId) {
  try {
    return (await chrome.tabs.get(tabId))?.url;
  } catch {
    return undefined;
  }
}

/**
 * Did this failure destroy the tool's result rather than the tool's action?
 *
 * Matched narrowly and deliberately. Upstream ALREADY recovers results across
 * script navigation, form navigation and new-tab handoff — the e2e suite proves
 * it with four passing assertions — and those calls resolve rather than throwing,
 * so they never reach here. Broadening this test would reclassify working
 * behaviour as `lost`, which is a regression, not a feature.
 */
function isLostToNavigation(error) {
  return /cannot return tool results after a cross-origin navigation/i.test(
    String(error?.message ?? error),
  );
}

/**
 * Does this tool have outward-facing side effects?
 *
 * Precedence, highest first:
 *   1. `readOnlyHint: true` — authoritative. A tool the page declares read-only
 *      is never destructive, whatever it's called.
 *   2. The name heuristic (context.md#Destructive tool).
 *
 * `destructiveHint` is NOT consulted, and cannot be: the Chrome Origin Trial
 * puts exactly two keys on `annotations` — `readOnlyHint` and
 * `untrustedContentHint` — so a page that correctly declares
 * `destructiveHint: true` is invisible to any extension, ours included. Measured
 * against a fixture that declares it, not assumed; the e2e suite carries a
 * canary that goes red the day Chrome adds the field. See
 * docs/adr/0004-forward-destructive-hint.md for the attempt and the revert.
 *
 * Consequence to be honest about: annotations can CLEAR a tool but not FLAG one.
 */
function isDestructive(tool) {
  if (tool?.readOnlyHint) return false;
  // Separator-agnostic: real tools use hyphens (optimizely-…-submit) and the
  // fixtures use underscores (submit_order). Both must match.
  return /(^|[-_])(submit|delete|purchase)([-_]|$)/i.test(tool?.name ?? '');
}

function getFormattedDate() {
  const today = new Date();
  return today.toLocaleDateString('en-US', {
    weekday: 'long',
    year: 'numeric',
    month: 'long',
    day: 'numeric',
  });
}

function getConfig() {
  const systemInstruction = [
    'You are an assistant embedded in a browser tab.',
    'User prompts typically refer to the current tab unless stated otherwise.',
    'Use the provided tools to query page content when you need it.',
    `Today's date is: ${getFormattedDate()}`,
    'CRITICAL RULE: Whenever the user provides a relative date (e.g., "next Monday", "tomorrow", "in 3 days"),  you must calculate the exact calendar date based on today\'s date.',
    'CRITICAL RULE: Do not try to use other tools than the available ones.',
  ];

  // `?? []` guards the same upstream crash the `?.` at the toolCall lookup
  // does. A tool that navigates the page (e.g. a search-results tool) kills the
  // content script AND delivers a tool-less message, so the tool-response turn
  // that follows built its config from an undefined list and threw
  // "Cannot read properties of undefined (reading 'map')" — after the tool
  // error itself had already been handled cleanly.
  const functionDeclarations = (currentTools ?? []).map((tool) => {
    return {
      name: `_${tool.frameId}_${tool.name}`,
      description: tool.description,
      parametersJsonSchema: tool.inputSchema
        ? JSON.parse(tool.inputSchema)
        : { type: 'object', properties: {} },
    };
  });
  return { systemInstruction, tools: [{ functionDeclarations }] };
}

function generateTemplateFromSchema(schema) {
  if (!schema || typeof schema !== 'object') {
    return null;
  }

  if (schema.hasOwnProperty('const')) {
    return schema.const;
  }

  if (Array.isArray(schema.oneOf) && schema.oneOf.length > 0) {
    return generateTemplateFromSchema(schema.oneOf[0]);
  }

  if (schema.hasOwnProperty('default')) {
    return schema.default;
  }

  if (Array.isArray(schema.examples) && schema.examples.length > 0) {
    return schema.examples[0];
  }

  switch (schema.type) {
    case 'object':
      const obj = {};
      if (schema.properties) {
        Object.keys(schema.properties).forEach((key) => {
          obj[key] = generateTemplateFromSchema(schema.properties[key]);
        });
      }
      return obj;

    case 'array':
      if (schema.items) {
        return [generateTemplateFromSchema(schema.items)];
      }
      return [];

    case 'string':
      if (schema.enum && schema.enum.length > 0) {
        return schema.enum[0];
      }
      if (schema.format === 'date') {
        return new Date().toISOString().substring(0, 10);
      }
      // yyyy-MM-ddThh:mm:ss.SSS
      if (
        schema.format ===
        '^[0-9]{4}-(0[1-9]|1[0-2])-[0-9]{2}T([01][0-9]|2[0-3]):[0-5][0-9](:[0-5][0-9](\\.[0-9]{1,3})?)?$'
      ) {
        return new Date().toISOString().substring(0, 23);
      }
      // yyyy-MM-ddThh:mm:ss
      if (
        schema.format ===
        '^[0-9]{4}-(0[1-9]|1[0-2])-[0-9]{2}T([01][0-9]|2[0-3]):[0-5][0-9](:[0-5][0-9])?$'
      ) {
        return new Date().toISOString().substring(0, 19);
      }
      // yyyy-MM-ddThh:mm
      if (schema.format === '^[0-9]{4}-(0[1-9]|1[0-2])-[0-9]{2}T([01][0-9]|2[0-3]):[0-5][0-9]$') {
        return new Date().toISOString().substring(0, 16);
      }
      // yyyy-MM
      if (schema.format === '^[0-9]{4}-(0[1-9]|1[0-2])$') {
        return new Date().toISOString().substring(0, 7);
      }
      // yyyy-Www
      if (schema.format === '^[0-9]{4}-W(0[1-9]|[1-4][0-9]|5[0-3])$') {
        return `${new Date().toISOString().substring(0, 4)}-W01`;
      }
      // HH:mm:ss.SSS
      if (schema.format === '^([01][0-9]|2[0-3]):[0-5][0-9](:[0-5][0-9](\\.[0-9]{1,3})?)?$') {
        return new Date().toISOString().substring(11, 23);
      }
      // HH:mm:ss
      if (schema.format === '^([01][0-9]|2[0-3]):[0-5][0-9](:[0-5][0-9])?$') {
        return new Date().toISOString().substring(11, 19);
      }
      // HH:mm
      if (schema.format === '^([01][0-9]|2[0-3]):[0-5][0-9]$') {
        return new Date().toISOString().substring(11, 16);
      }
      if (schema.format === '^#[0-9a-zA-Z]{6}$') {
        return '#ff00ff';
      }
      if (schema.format === 'tel') {
        return '123-456-7890';
      }
      if (schema.format === 'email') {
        return 'user@example.com';
      }
      return 'example_string';

    case 'number':
    case 'integer':
      if (schema.minimum !== undefined) return schema.minimum;
      return 0;

    case 'boolean':
      return false;

    case 'null':
      return null;

    default:
      return {};
  }
}

function waitForPageLoad(tabId) {
  return new Promise((resolve) => {
    let timeoutId;
    const done = () => {
      clearTimeout(timeoutId);
      chrome.tabs.onUpdated.removeListener(listener);
      resolve();
    };
    const listener = (updatedTabId, changeInfo) => {
      if (updatedTabId === tabId && changeInfo.status === 'complete') done();
    };

    timeoutId = setTimeout(done, 5000); // resolve rather than reject to avoid crashing the AI loop
    chrome.tabs.onUpdated.addListener(listener);

    // The tab may already be done loading, or gone; don't wait on the
    // timeout for those.
    chrome.tabs.get(tabId).then((tab) => {
      if (tab.status === 'complete') done();
    }).catch(done);
  });
}

