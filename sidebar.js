// Listen for the results coming back from content.js
chrome.runtime.onMessage.addListener(async ({ message, tools, url, type }, sender) => {
  // Internal signals (e.g. contentScriptReady) are handled elsewhere.
  if (type) return;
  if (sender.frameId && sender.frameId !== 0) return;

  const [tab] = await chrome.tabs.query({ active: true, currentWindow: true });
  if (sender.tab && sender.tab.id !== tab.id) return;

  tbody.innerHTML = '';
  thead.innerHTML = '';
  toolNames.innerHTML = '';

  statusDiv.textContent = message;
  statusDiv.hidden = !message;

  const haveNewTools = JSON.stringify(currentTools) !== JSON.stringify(tools);

  currentTools = tools ?? [];

  if (!tools || tools.length === 0) {
    const row = document.createElement('tr');
    row.innerHTML = `<td colspan="100%"><i>No tools registered yet in ${url || tab.url}</i></td>`;
    tbody.appendChild(row);
    inputArgsText.value = '';
    inputArgsText.disabled = true;
    toolNames.disabled = true;
    executeBtn.disabled = true;
    copyToClipboard.hidden = true;
    return;
  }

  inputArgsText.disabled = false;
  toolNames.disabled = false;
  executeBtn.disabled = false;
  copyToClipboard.hidden = false;

  const KEYS = ['description', 'inputSchema', 'readOnlyHint', 'untrustedContentHint', 'name'];
  const keys = KEYS.filter((key) => tools.some((tool) => key in tool));
  keys.forEach((key) => {
    const th = document.createElement('th');
    th.textContent = key;
    thead.appendChild(th);
  });

  tools.forEach((item) => {
    const row = document.createElement('tr');
    keys.forEach((key) => {
      const td = document.createElement('td');
      const pre = document.createElement('pre');
      try {
        pre.textContent = JSON.stringify(JSON.parse(item[key]), '', '  ');
        td.appendChild(pre);
      } catch (error) {
        // `?? ''` because an absent hint arrives as the key present with an
        // undefined value (content.js), and textContent stringifies undefined
        // to the literal "undefined" — noise in a table whose job is showing
        // exactly what the page declared. Blank means undeclared.
        td.textContent = item[key] ?? '';
      }
      row.appendChild(td);
    });
    tbody.appendChild(row);

    const option = document.createElement('option');
    option.textContent = `"${item.name}"${item.frameId !== 0 ? ` (${item.frameId})` : ''}`;
    option.value = item.name;
    option.dataset.inputSchema = item.inputSchema || '{}';
    option.dataset.frameId = item.frameId;
    toolNames.appendChild(option);
  });
  updateDefaultValueForInputArgs();
  renderChips(tools);

  if (haveNewTools) suggestUserPrompt();
});

/**
 * Opener chips (issue 0005): one per registered tool, derived deterministically
 * from the tool list — never generated by the model.
 *
 * They double as a live readout of what the agent can reach on this page, so a
 * missing chip is a registration bug you can see before typing anything.
 * Clicking one only populates the composer; nothing is executed.
 */
function renderChips(tools) {
  chips.textContent = '';
  for (const tool of tools ?? []) {
    const chip = document.createElement('button');
    chip.type = 'button';
    chip.className = isDestructive(tool) ? 'chip dstr' : 'chip';
    chip.textContent = isDestructive(tool) ? `❗ ${tool.name}` : tool.name;
    chip.title = tool.description ?? tool.name;
    chip.dataset.tool = tool.name;
    chip.addEventListener('click', () => {
      userPromptText.value = `Use ${tool.name} on this page.`;
      userPromptText.focus();
    });
    chips.appendChild(chip);
  }
}

